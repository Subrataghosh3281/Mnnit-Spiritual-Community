-- 1. Events Table
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'Festival',
    date DATE NOT NULL,
    time TEXT,
    venue TEXT NOT NULL,
    status TEXT DEFAULT 'Upcoming' CHECK (status IN ('Upcoming', 'Completed')),
    description TEXT,
    image TEXT,
    featured BOOLEAN DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Gallery Table
CREATE TABLE IF NOT EXISTS public.gallery (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'Performances',
    description TEXT,
    date TEXT,
    image TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Student Applications / Join Submissions Table
CREATE TABLE IF NOT EXISTS public.applications (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    year TEXT NOT NULL,
    branch TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT NOT NULL,
    skills TEXT[] DEFAULT '{}',
    why_to_join TEXT,
    spiritual_or_music_activity TEXT,
    event_title TEXT,
    type TEXT DEFAULT 'club_membership',
    submitted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Site Settings Table
CREATE TABLE IF NOT EXISTS public.site_settings (
    id INT PRIMARY KEY DEFAULT 1,
    tagline TEXT,
    headline TEXT,
    subheadline TEXT,
    whatsapp_group_link TEXT,
    google_form_link TEXT,
    email TEXT,
    instagram_link TEXT,
    location TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- Row Level Security (RLS) Policies
-- ==============================================================================
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;

-- Events: Everyone can view, authenticated users can insert/update/delete
CREATE POLICY "Public events are viewable by everyone" ON public.events
    FOR SELECT USING (true);

CREATE POLICY "Admins can insert events" ON public.events
    FOR INSERT WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Admins can update events" ON public.events
    FOR UPDATE USING (auth.role() = 'authenticated');

CREATE POLICY "Admins can delete events" ON public.events
    FOR DELETE USING (auth.role() = 'authenticated');

-- Gallery: Everyone can view, authenticated users can insert/delete
CREATE POLICY "Public gallery photos viewable by everyone" ON public.gallery
    FOR SELECT USING (true);

CREATE POLICY "Admins can insert gallery photos" ON public.gallery
    FOR INSERT WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Admins can delete gallery photos" ON public.gallery
    FOR DELETE USING (auth.role() = 'authenticated');

-- Applications: Anyone can submit their application; only admins can view
CREATE POLICY "Anyone can submit a membership application" ON public.applications
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Admins can view membership applications" ON public.applications
    FOR SELECT USING (auth.role() = 'authenticated');

-- Site Settings: Everyone can view; authenticated users can update
CREATE POLICY "Public site settings are viewable by everyone" ON public.site_settings
    FOR SELECT USING (true);

CREATE POLICY "Admins can update site settings" ON public.site_settings
    FOR UPDATE USING (auth.role() = 'authenticated');
